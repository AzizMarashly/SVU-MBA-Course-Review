for ch in (1, 2, 3, 5, 7, 8, 9, 10):
    items = [x for x in Q if x['ch'] == ch]
    blob[ch] = [(x['id'], norm(x['text'] + ' | ' + ' | '.join(x['opts']) + ' | ' + x['ans']),
                 norm(x['exp'])) for x in items]

gaps, weak = [], []
for ch, sid, label, kws in C:
    kn = [norm(k) for k in kws]
    hits_q = [i for i, q_, e_ in blob[ch] if any(k in q_ for k in kn)]
    hits_e = [i for i, q_, e_ in blob[ch] if any(k in e_ for k in kn)]
    if hits_q:
        continue
    (weak if hits_e else gaps).append((ch, sid, label, len(hits_e)))

print('=' * 78)
print('NOT ASKED ANYWHERE (nothing in any question text/options/answer):', len(gaps))
print('=' * 78)
for ch, sid, label, _ in gaps:
    print('  ch%-3s %-9s %s' % (ch, sid, label))
print()
print('=' * 78)
print('ONLY INSIDE EXPLANATIONS (mentioned, never actually asked):', len(weak))
print('=' * 78)
